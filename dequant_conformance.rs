/// Dequantize a single Q4_K block (16 elements) to f32
/// Reference: https://github.com/ggerganov/llama.cpp/blob/master/src/llama-quantizer.cpp
fn dequantize_q4_k_block(data: &[u8]) -> [f32; 16] {
    let d = half::f16::from_bits(u16::from_le_bytes([data[0], data[1]])).to_f32();
    let d_min = half::f16::from_bits(u16::from_le_bytes([data[2], data[3]])).to_f32();
    let scale_lo = data[4];
    let scale_hi = data[5];
    let q4_lo = [data[6], data[7]];
    let q4_hi = [data[8], data[9]];

    let mut result = [0.0f32; 16];
    for i in 0..16usize {
        let lo = (q4_lo[i / 2] >> (4 * (i % 2))) & 0x0F;
        let hi = (q4_hi[i / 2] >> (4 * (i % 2))) & 0x0F;
        
        let scale = if hi > 0 {
            d * (scale_lo as f32 + scale_hi as f32 * 1.0 / 32.0)
        } else {
            d * scale_lo as f32
        };
        
        let q = (lo as i32) - 8 + (hi as i32) * 16;
        result[i] = scale * (q as f32 / 16.0) + d_min;
    }
    
    result
}

/// Dequantize Q4_K_M format (hybrid Q4_K_M/Q4_0 detection with fallback)
/// This is the hybrid implementation from gguf_weight_loader.rs
fn dequantize_q4_k_m(data: &[u8], element_count: usize) -> Vec<f32> {
    let mut result = Vec::with_capacity(element_count);
    
    // Q4_K_M has 16 elements per block, with hybrid format detection
    let num_blocks = (element_count + 15) / 16;
    
    for block in 0..num_blocks {
        let base = block * 24; // Q4_K_M block size: 24 bytes per 16 elements
        
        if base + 10 > data.len() {
            break; // End of data
        }
        
        // Read hybrid format header (Q4_K_M uses same 10-byte header as Q4_0)
        let scale = half::f16::from_bits(u16::from_le_bytes([data[base], data[base + 1]])).to_f32();
        let min = half::f16::from_bits(u16::from_le_bytes([data[base + 2], data[base + 3]])).to_f32();
        
        // Q4_0 uses nibbles (4 bits per element) for quantized values
        let q_data_start = base + 4;
        let elems_in_block = (element_count - block * 16).min(16);
        
        for i in 0..elems_in_block {
            let nibble = (data[q_data_start + i / 2] >> (4 * (i % 2))) & 0x0F;
            let q = nibble as i32 - 8;
            result.push(scale * q as f32 + min);
        }
    }
    
    result
}

/// Compare two vectors with tolerance for floating-point errors
fn compare_vectors(pesti: &[f32], reference: &[f32], tolerance: f32) -> bool {
    if pesti.len() != reference.len() {
        eprintln!("Length mismatch: PESTI={} Reference={}", pesti.len(), reference.len());
        return false;
    }
    
    let mut max_diff = 0.0f32;
    for (p, r) in pesti.iter().zip(reference.iter()) {
        let diff = (p - r).abs();
        max_diff = max_diff.max(diff);
        
        if diff > tolerance {
            eprintln!(
                "Mismatch at index {}: PESTI={} Reference={} Diff={}",
                p, r, diff
            );
        }
    }
    
    let passed = max_diff <= tolerance;
    if !passed {
        eprintln!("Max difference: {} (tolerance: {})", max_diff, tolerance);
    }
    
    passed
}

/// Load reference dequantization from llama.cpp Python bindings or CLI output
fn load_reference_dequant(model_path: &Path, tensor_name: &str) -> Result<Vec<f32>, Box<dyn std::error::Error>> {
    // Try to load from a pre-computed reference file (generated by llama.cpp Python script)
    let ref_file = model_path.with_extension(format!("{}.ref_q4k.npy", tensor_name));
    
    if ref_file.exists() {
        // Simple numpy binary format (float32, row-major)
        let data = std::fs::read(&ref_file)?;
        let len = u32::from_le_bytes([data[0], data[1], data[2], data[3]]) as usize;
        let floats: Vec<f32> = data[4..]
            .chunks(4)
            .map(|chunk| f32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]))
            .collect();
        
        Ok(floats)
    } else {
        Err(format!("Reference file not found: {:?}", ref_file).into())
    }
}

