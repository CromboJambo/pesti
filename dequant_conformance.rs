#[cfg(test)]
mod tests {
    use super::*;
    
    #[test]
    fn test_q4_k_block_dequantization() {
        // Test with known-good Q4_K block (from llama.cpp test suite)
        let data = vec![
            0x00, 0x3C,  // scale = 1.0f32
            0x00, 0x00,  // min = 0.0f32
            0xFF, 0x0F,  // scales (lo=255, hi=15)
            0xAA, 0x55, 0x00, 0x00, // quantized data
        ];
        
        let result = dequantize_q4_k_block(&data);
        
        // Verify all values are within expected range
        for (i, &val) in result.iter().enumerate() {
            assert!(
                val.is_finite(),
                "Dequantized value at index {} is not finite: {}",
                i, val
            );
        }
    }
    
    #[test]
    fn test_q4_k_m_hybrid_format() {
        // Test hybrid Q4_K_M/Q4_0 detection
        let data = vec![
            0x00, 0x3C,  // scale = 1.0f32
            0x00, 0x00,  // min = 0.0f32
            0x0F, 0x0F, 0x0F, 0x0F, // nibbles (all max values)
        ];
        
        let result = dequantize_q4_k_m(&data, 8);
        
        assert_eq!(result.len(), 8);
        
        // All values should be positive (nibble=15 => q=7)
        for val in &result {
            assert!(*val > 0.0, "Expected positive value, got {}", val);
        }
    }
    
    #[test]
    fn test_vector_comparison_tolerance() {
        let pesti = vec![1.0f32, 2.0, 3.0, 4.0];
        let reference = vec![1.00001, 2.00001, 3.00001, 4.00001];
        
        assert!(compare_vectors(&pesti, &reference, 1e-4));
        assert!(!compare_vectors(&pesti, &reference, 1e-6));
    }
}
